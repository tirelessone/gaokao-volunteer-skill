def classify_major_groups(data):
    # 分割数据为不同的专业组
    groups = data.strip().split('\n\n')

    # 定义三个类别
    chong = []  # 冲
    wen = []  # 稳
    bao = []  # 保

    for group in groups:
        if not group.strip():
            continue

        # 提取专业组概率
        match = re.search(r'专业组概率:(\d+)%', group)
        if match:
            probability = int(match.group(1))

            # 根据概率分类
            if probability <= 50:
                chong.append(group)
            elif probability <= 80:  # 50-80%（包括80%）
                wen.append(group)
            else:  # >80%
                bao.append(group)

    # 构建结果字符串
    result = ""

    if chong:
        result += "属于\"冲\"的专业组有：\n"
        result += "\n\n".join(chong)
        result += "\n\n"

    if wen:
        result += "属于\"稳\"的专业组有：\n"
        result += "\n\n".join(wen)
        result += "\n\n"

    if bao:
        result += "属于\"保\"的专业组有：\n"
        result += "\n\n".join(bao)

    return result

